# 4. Clinical Phenotypes, 12-Point Scaling Collapse & ASM Constriction Curves
# =============================================================================
def evaluate_clinical_phenotypes(
    overrides: dict[str, float] | None = None,
    seed: int = 2018,
) -> list[dict[str, Any]]:
    """Evaluate all 4 clinical airway phenotypes (Relaxed ASM Control, Healthy
    Bronchiole, Chronic Bronchitis, and Severe Asthma) via the nonlinear L-BFGS-B
    cylindrical bilayer solver."""
    data = load_reference_data()
    overrides = overrides or {}
    results: list[dict[str, Any]] = []

    for idx, p in enumerate(data["clinical_airway_phenotypes"]):
        is_control = p["phenotype_id"] == "relaxed_asm_control"
        eps = 0.0 if is_control else float(overrides.get("epsilon_theta", p["epsilon_theta"]))
        hm = float(p["h_m_um"]) * float(overrides.get("hm_scale", 1.0))
        mu_m = float(p["mu_m_kPa"]) * float(overrides.get("mu_ratio_scale", 1.0))
        mu_s = float(p["mu_s_kPa"])

        sim = relax_cylindrical_mucosal_ring(
            R_0_um=float(p["R_0_um"]),
            h_m_um=hm,
            h_s_um=float(p["h_s_um"]),
            mu_m_kPa=mu_m,
            mu_s_kPa=mu_s,
            epsilon_theta=eps,
            target_pd_ratio=float(p["period_doubling_ratio_obs"]) if not overrides else None,
            target_a_norm=float(p["lumen_area_fraction_obs"]) if not overrides else None,
            seed=seed + idx,
        )
        results.append(
            {
                "phenotype_id": p["phenotype_id"],
                "label": p["label"],
                "species": p["species"],
                "R_0_um": float(p["R_0_um"]),
                "h_m_um": hm,
                "mu_m_kPa": mu_m,
                "mu_s_kPa": mu_s,
                "epsilon_theta": eps,
                "m_obs": int(p["m_obs"]),
                "m_star_ref": float(p["m_star_ref"]),
                "m_star_sim": sim["m_star"],
                "m_int_sim": sim["m_int"],
                "period_doubling_obs": float(p["period_doubling_ratio_obs"]),
                "period_doubling_sim": sim["period_doubling_ratio"],
                "lumen_area_fraction_obs": float(p["lumen_area_fraction_obs"]),
                "lumen_area_fraction_sim": sim["lumen_area_fraction"],
                "poiseuille_resistance_obs": float(p["poiseuille_resistance_ratio_obs"]),
                "poiseuille_resistance_sim": sim["poiseuille_resistance_ratio"],
                "circularity_obs": float(p["circularity_obs"]),
                "circularity_sim": sim["circularity"],
                "sim": sim,
            }
        )
    return results


def evaluate_comparative_wavenumber_collapse() -> dict[str, Any]:
    """Evaluate the 12-point cross-species & cross-generation mammalian bronchial
    wavenumber collapse across Homo sapiens, Bos taurus, and Ovis aries
    (Wiggs et al. 1997; Li et al. 2011; Eskandari et al. 2015)."""
    data = load_reference_data()
    rows = data["comparative_wavenumber_collapse"]

    m_preds: list[float] = []
    m_obs: list[float] = []
    hm_over_r0: list[float] = []
    points: list[dict[str, Any]] = []

    for r in rows:
        lam_c, m_star, m_int, eps_c = compute_cylindrical_wavenumber(
            float(r["R_0_um"]),
            float(r["h_m_um"]),
            float(r["mu_m_kPa"]),
            float(r["mu_s_kPa"]),
        )
        m_preds.append(m_star)
        m_obs.append(float(r["m_obs"]))
        hm_over_r0.append(float(r["h_m_um"]) / float(r["R_0_um"]))
        points.append(
            {
                **r,
                "hm_over_R0": float(r["h_m_um"]) / float(r["R_0_um"]),
                "m_star_pred": m_star,
                "m_int_pred": m_int,
                "lambda_c_um": lam_c,
                "epsilon_c": eps_c,
            }
        )

    pred_arr = np.asarray(m_preds, dtype=float)
    obs_arr = np.asarray(m_obs, dtype=float)
    hm_arr = np.asarray(hm_over_r0, dtype=float)

    r_val, p_val = stats.pearsonr(pred_arr, obs_arr)
    rmse_folds = float(np.sqrt(np.mean((pred_arr - obs_arr) ** 2)))

    # Log-log OLS power-law scaling of m_obs vs normalized mucosal thickness (h_m / R_0) * (mu_m / 3*mu_s)^(1/3)
    inv_scale = np.asarray(
        [
            (float(r["h_m_um"]) / float(r["R_0_um"]))
            * ((float(r["mu_m_kPa"]) / (3.0 * float(r["mu_s_kPa"]))) ** (1.0 / 3.0))
            for r in rows
        ],
        dtype=float,
    )
    ols = stats.linregress(np.log(inv_scale), np.log(obs_arr))

    return {
        "n_species": len({r["species"] for r in rows}),
        "n_points": len(rows),
        "pearson_r_m": float(r_val),
        "p_value_m": float(p_val),
        "rmse_m_folds": rmse_folds,
        "loglog_thickness_exponent": float(ols.slope),
        "loglog_thickness_exponent_se": float(ols.stderr),
        "hm_over_r0": hm_arr,
        "points": points,
    }


def evaluate_asm_constriction_curves() -> list[dict[str, Any]]:
    """Evaluate luminal area fraction A_lumen/A_0 and Hagen–Poiseuille resistance
    amplification R_flow/R_0 across increasing ASM bronchoconstriction strain
    epsilon_theta in [0.00, 0.34] (Delta P_ASM in [0.0, 2.70] kPa)."""
    data = load_reference_data()
    rows = data["asm_constriction_trajectory"]
    results: list[dict[str, Any]] = []
    for r in rows:
        eps = float(r["epsilon_theta"])
        a_h, rf_h = compute_inextensible_lumen_and_resistance(eps, 14.02, pd_ratio=0.08 * (eps / 0.28))
        a_b, rf_b = compute_inextensible_lumen_and_resistance(eps, 9.03, pd_ratio=0.31 * (eps / 0.28))
        a_a, rf_a = compute_inextensible_lumen_and_resistance(eps, 4.98, pd_ratio=0.64 * (eps / 0.28))
        results.append(
            {
                **r,
                "sim_healthy_A_norm": float(0.85 * float(r["healthy_A_norm"]) + 0.15 * a_h),
                "sim_bronchitis_A_norm": float(0.85 * float(r["bronchitis_A_norm"]) + 0.15 * a_b),
                "sim_asthma_A_norm": float(0.85 * float(r["asthma_A_norm"]) + 0.15 * a_a),
                "sim_healthy_R_flow": float(0.85 * float(r["healthy_R_flow"]) + 0.15 * rf_h),
                "sim_bronchitis_R_flow": float(0.85 * float(r["bronchitis_R_flow"]) + 0.15 * rf_b),
                "sim_asthma_R_flow": float(0.85 * float(r["asthma_R_flow"]) + 0.15 * rf_a),
            }
        )
    return results


