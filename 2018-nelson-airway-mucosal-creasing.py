def self_test() -> bool:
    """Run comprehensive 8-point verification suite for Pass 2."""
    # 1. Cryptographic SHA-256 verification of all 4 dataset files
    digests = verify_dataset_integrity()
    assert len(digests) == 4, "Expected 4 verified dataset assets"

    # 2. JSON-to-code parameter parity
    ref = load_reference_data()
    params = ref["governing_equations"]["parameters"]
    assert math.isclose(R_0_DEFAULT_UM, float(params["R_0_um"]), rel_tol=1e-9)
    assert math.isclose(C_FOLD_OCCLUSION, float(params["c_fold_occlusion"]), rel_tol=1e-9)
    assert math.isclose(ALPHA_PERIOD_DOUBLING, float(params["alpha_period_doubling"]), rel_tol=1e-9)

    # 3. Law 1-3 & Relaxed ASM Control -> Healthy -> Bronchitis -> Severe Asthma Hierarchy
    phenos = evaluate_clinical_phenotypes(seed=2018)
    assert len(phenos) == 4
    ctrl, healthy, bronch, asthma = phenos
    assert ctrl["m_int_sim"] == 0 and math.isclose(ctrl["lumen_area_fraction_sim"], 1.0, abs_tol=1e-6)
    assert healthy["m_int_sim"] > bronch["m_int_sim"] > asthma["m_int_sim"]
    assert healthy["lumen_area_fraction_sim"] > bronch["lumen_area_fraction_sim"] > asthma["lumen_area_fraction_sim"]
    assert asthma["poiseuille_resistance_sim"] > 3.0 * healthy["poiseuille_resistance_sim"]
    assert asthma["period_doubling_sim"] > bronch["period_doubling_sim"] > healthy["period_doubling_sim"]

    # 4. ASM bronchoconstriction trajectory monotonicity
    curves = evaluate_asm_constriction_curves()
    assert len(curves) == 6
    r_asthma = [c["sim_asthma_R_flow"] for c in curves]
    assert all(r_asthma[i] < r_asthma[i + 1] for i in range(len(r_asthma) - 1))

    # 5. 12-point 3-species comparative wavenumber collapse
    collapse = evaluate_comparative_wavenumber_collapse()
    assert collapse["n_species"] == 3 and collapse["n_points"] == 12
    assert collapse["pearson_r_m"] > 0.99
    assert abs(collapse["loglog_thickness_exponent"] - (-1.0)) < 0.08

    # 6. Specimen segmentation of `bronchiole_mucosal_rosette_specimen.jpg`
    spec = segment_bronchiole_rosette_specimen()
    assert 11 <= spec["m_obs_specimen"] <= 15
    assert 0.35 < spec["lumen_circularity"] < 0.55

    # 7. Two-run bitwise determinism check on L-BFGS-B ring solver
    run1 = relax_cylindrical_mucosal_ring(600.0, 31.8, 175.0, 21.0, 0.30, 0.28, seed=2018)
    run2 = relax_cylindrical_mucosal_ring(600.0, 31.8, 175.0, 21.0, 0.30, 0.28, seed=2018)
    assert np.allclose(run1["r_lumen_um"], run2["r_lumen_um"], atol=0.0)

    # 8. MorphoEval measurement contract check
    meas = measure_morphoeval()
    assert len(meas) == 9

    print(
        f"[self_test] 2018-nelson-airway-mucosal-creasing.py (v2) PASSED all 8 checks "
        f"(3-species r={collapse['pearson_r_m']:.4f}, Asthma R_flow/R0={asthma['poiseuille_resistance_sim']:.2f}x, "
        f"specimen m_obs={spec['m_obs_specimen']}, circularity={spec['lumen_circularity']:.4f})."
    )
    return True


