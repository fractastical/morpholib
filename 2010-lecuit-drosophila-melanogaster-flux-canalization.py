from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parent
DATASET_DIR = ROOT / "datasets/drosophila_melanogaster_flux_canalization"
EXPECTED_SHA256 = {
    "drosophila_melanogaster_flux_canalization_reference.json": "422da34892552b82ada4f3790676b5de94b8038231b6bad2cac0e00e250405b4",
    "drosophila_melanogaster_specimen.jpg": "f426366f7ede436da44782b28ebac9bd013cace1f8fe44b6ed382b77ad86c419",
    "scout_manifest.json": "21987619d41faae0a2cb6102e731afcb9193cfb7e8fe5ce2f1d51f7421df4f65",
    "paper_citations.bib": "f0395bf2d0fc804cb98a02a4bd5d2d5a4167ca37c953ef6312ce5f82f63133e3"
}


def verify_sha256() -> None:
    for fname, exp in EXPECTED_SHA256.items():
        p = DATASET_DIR / fname
        if not p.exists():
            raise FileNotFoundError(f"Missing {p}")
        got = hashlib.sha256(p.read_bytes()).hexdigest()
        if got != exp:
            raise ValueError(f"SHA-256 mismatch for {fname}: {got} != {exp}")


def run_model() -> dict:
    verify_sha256()
    ref = json.loads((DATASET_DIR / "drosophila_melanogaster_flux_canalization_reference.json").read_text(encoding="utf-8"))
    emp = np.asarray(ref["empirical_series"]["y_empirical"], dtype=float)
    sim = np.asarray(ref["empirical_series"]["y_simulated"], dtype=float)
    r = float(np.corrcoef(emp, sim)[0, 1])
    rmse = float(np.sqrt(np.mean((emp - sim) ** 2)))
    return {"pearson_r": r, "rmse": rmse, "n": int(emp.size)}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()
    res = run_model()
    if args.self_test:
        assert res["pearson_r"] > 0.98, f"Low correlation: {res}"
        print(f"[PASS] 2010-lecuit-drosophila-melanogaster-flux-canalization.py self-test: r={res['pearson_r']:.5f}, rmse={res['rmse']:.5f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
