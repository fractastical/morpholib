# 2. Governing Cylindrical Bilayer Buckling & Poiseuille Laws (Lean Loop_068)
# =============================================================================
def compute_cylindrical_wavenumber(
    R_0_um: float,
    h_m_um: float,
    mu_m_kPa: float,
    mu_s_kPa: float,
) -> tuple[float, float, int, float]:
    """Compute critical buckling wavelength lambda_c, continuous mode number m*,
    integer rosette fold number m_int, and critical buckling strain epsilon_c
    (linked to `MathOfBiology.Loop_068.inverse_mucosal_thickness_fold_scaling`)."""
    if R_0_um <= 0.0 or h_m_um <= 0.0 or mu_m_kPa <= 0.0 or mu_s_kPa <= 0.0:
        raise ValueError("Airway radius, mucosal thickness, and shear moduli must be strictly positive")
    modulus_term = (3.0 * mu_s_kPa / mu_m_kPa) ** (1.0 / 3.0)
    # Li et al. (2011) JMPS & Eskandari et al. (2015) JTB cylindrical bilayer scaling
    wall_coupling = (1.0 + 0.0085 * h_m_um) ** (-0.5)
    m_star = float(C_CYL_CURVATURE * wall_coupling * (R_0_um / h_m_um) * modulus_term)
    m_int = max(int(round(m_star)), 2)
    lambda_c = float(2.0 * math.pi * R_0_um / max(m_star, 1e-6))
    epsilon_c = float(0.25 * ((3.0 * mu_s_kPa / mu_m_kPa) ** (2.0 / 3.0)))
    return lambda_c, m_star, m_int, epsilon_c


def compute_inextensible_lumen_and_resistance(
    epsilon_theta: float,
    m_star: float,
    pd_ratio: float = 0.0,
    c_fold: float = C_FOLD_OCCLUSION,
) -> tuple[float, float]:
    """Compute open luminal cross-sectional area fraction A_lumen / A_0 and
    Hagen–Poiseuille airflow resistance amplification R_flow / R_0 = (A_0 / A_lumen)^2
    (linked to `MathOfBiology.Loop_068.inextensible_perimeter_lumen_occlusion` and
    `MathOfBiology.Loop_068.poiseuille_quadratic_area_resistance_amplification`)."""
    if epsilon_theta <= 0.0 or m_star <= 0.0:
        return 1.0, 1.0
    outer_shrink = (1.0 - epsilon_theta) ** 2
    # Primary fold intrusion + post-buckling period-doubling & sulcal creasing occlusion
    fold_loss = (c_fold * epsilon_theta / max(m_star, 1.0)) * (1.0 + 0.68 * (pd_ratio**1.35))
    a_norm = float(np.clip(outer_shrink - fold_loss, 0.12, 1.0))
    r_flow = float(1.0 / (a_norm**2))
    return a_norm, r_flow


def predict_period_doubling_ratio(
    h_m_um: float,
    R_0_um: float,
    epsilon_theta: float | np.ndarray,
    epsilon_c: float,
) -> float | np.ndarray:
    """Closed-form post-buckling period-doubling subharmonic ratio A_{m/2}/A_m used by
    both the 1D ring solver (`relax_cylindrical_mucosal_ring`) and the Pass 3 tree
    network. Grows with mucosal thickness h_m/R_0 and supercritical strain
    (epsilon_theta - epsilon_c); clipped to [0.04, 0.72] (Eskandari et al. 2015 JTB).
    Accepts scalar or array epsilon_theta (vectorised for the 8191-branch tree)."""
    delta_eps = np.maximum(np.asarray(epsilon_theta, dtype=float) - epsilon_c, 0.0)
    thickness_ratio = h_m_um / R_0_um
    pd_raw = ALPHA_PERIOD_DOUBLING * (thickness_ratio / 0.022) ** 1.35 * (delta_eps / 0.22)
    pd = np.clip(pd_raw, 0.04, 0.72)
    return float(pd) if np.ndim(pd) == 0 else pd


def lumen_area_fraction_vectorized(
    epsilon_theta: np.ndarray,
    m_star: float,
    pd_ratio: np.ndarray,
    c_fold: float = C_FOLD_OCCLUSION,
) -> np.ndarray:
    """Vectorised twin of `compute_inextensible_lumen_and_resistance` (identical
    algebra, same 0.12 floor, A/A_0 = 1 for epsilon_theta <= 0) evaluated on a whole
    bronchial tree at once. Returns A_lumen / A_0 per branch."""
    eps = np.asarray(epsilon_theta, dtype=float)
    outer_shrink = (1.0 - eps) ** 2
    fold_loss = (c_fold * eps / max(m_star, 1.0)) * (1.0 + 0.68 * (np.asarray(pd_ratio, dtype=float) ** 1.35))
    a_norm = np.clip(outer_shrink - fold_loss, 0.12, 1.0)
    return np.where(eps <= 0.0, 1.0, a_norm)


