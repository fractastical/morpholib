def evaluate_comparative_wavenumber_collapse() -> dict[str, Any]:
    """Evaluate the 12-point cross-species & cross-generation mammalian bronchial
    wavenumber collapse across Homo sapiens, Bos taurus, and Ovis aries
    (Wiggs et al. 1997; Li et al. 2011; Eskandari et al. 2015)."""
    data = load_reference_data()
    rows = data["comparative_wavenumber_collapse"]

    m_preds: list[float] = []
    m_obs: list[float] = []
    hm_over_r0: list[float] = []
    points: list[dict[str, Any]] = []

    for r in rows:
        lam_c, m_star, m_int, eps_c = compute_cylindrical_wavenumber(
            float(r["R_0_um"]),
            float(r["h_m_um"]),
            float(r["mu_m_kPa"]),
            float(r["mu_s_kPa"]),
        )
        m_preds.append(m_star)
        m_obs.append(float(r["m_obs"]))
        hm_over_r0.append(float(r["h_m_um"]) / float(r["R_0_um"]))
        points.append(
            {
                **r,
                "hm_over_R0": float(r["h_m_um"]) / float(r["R_0_um"]),
                "m_star_pred": m_star,
                "m_int_pred": m_int,
                "lambda_c_um": lam_c,
                "epsilon_c": eps_c,
            }
        )

    pred_arr = np.asarray(m_preds, dtype=float)
    obs_arr = np.asarray(m_obs, dtype=float)
    hm_arr = np.asarray(hm_over_r0, dtype=float)

    r_val, p_val = stats.pearsonr(pred_arr, obs_arr)
    rmse_folds = float(np.sqrt(np.mean((pred_arr - obs_arr) ** 2)))

    # Log-log OLS power-law scaling of m_obs vs normalized mucosal thickness (h_m / R_0) * (mu_m / 3*mu_s)^(1/3)
    inv_scale = np.asarray(
        [
            (float(r["h_m_um"]) / float(r["R_0_um"]))
            * ((float(r["mu_m_kPa"]) / (3.0 * float(r["mu_s_kPa"]))) ** (1.0 / 3.0))
            for r in rows
        ],
        dtype=float,
    )
    ols = stats.linregress(np.log(inv_scale), np.log(obs_arr))

    return {
        "n_species": len({r["species"] for r in rows}),
        "n_points": len(rows),
        "pearson_r_m": float(r_val),
        "p_value_m": float(p_val),
        "rmse_m_folds": rmse_folds,
        "loglog_thickness_exponent": float(ols.slope),
        "loglog_thickness_exponent_se": float(ols.stderr),
        "hm_over_r0": hm_arr,
        "points": points,
    }


