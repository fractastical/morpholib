# 5. Computer-Vision Segmentation of `bronchiole_mucosal_rosette_specimen.jpg`
# =============================================================================
def segment_bronchiole_rosette_specimen() -> dict[str, Any]:
    """Segment the vendored CC BY-SA 2.0 transverse H&E histological micrograph of a
    mammalian bronchiole (`datasets/airway_mucosal_creasing/bronchiole_mucosal_rosette_specimen.jpg`),
    extracting the star-shaped luminal contour, observed inward mucosal fold count m_obs,
    fold intrusion peak coordinates, and lumen circularity 4*pi*A/P^2."""
    verify_dataset_integrity()
    im_rgb = np.asarray(Image.open(SPECIMEN_JPG).convert("RGB"), dtype=float) / 255.0
    # Crop ROI [80, 140, 1200, 860] containing the complete folded bronchiole cross-section
    roi = im_rgb[140:860, 80:1200]
    gray = 0.299 * roi[:, :, 0] + 0.587 * roi[:, :, 1] + 0.114 * roi[:, :, 2]

    # Smooth slightly and threshold bright central lumen vs dark purple mucosal epithelium
    smooth = ndi.gaussian_filter(gray, sigma=2.5)
    bright = smooth > np.percentile(smooth, 68)
    opened = ndi.binary_opening(bright, structure=np.ones((5, 5)))
    labeled, n_cc = ndi.label(opened)

    H, W = gray.shape
    cy0, cx0 = H / 2.0, W / 2.0
    best_lbl = max(
        range(1, n_cc + 1),
        key=lambda l: (labeled == l).sum()
        / (
            1.0
            + 0.02
            * math.hypot(
                float(np.nonzero(labeled == l)[1].mean()) - cx0,
                float(np.nonzero(labeled == l)[0].mean()) - cy0,
            )
        ),
    )
    lumen = labeled == best_lbl
    lumen = ndi.binary_closing(lumen, structure=np.ones((11, 11)))
    lumen = ndi.binary_fill_holes(lumen)

    yy, xx = np.nonzero(lumen)
    cx, cy = float(xx.mean()), float(yy.mean())

    eroded = ndi.binary_erosion(lumen, structure=np.ones((3, 3)))
    by, bx = np.nonzero(lumen & (~eroded))
    angles = np.arctan2(by - cy, bx - cx)
    radii = np.hypot(bx - cx, by - cy)

    n_bins = 360
    theta_grid = np.linspace(-math.pi, math.pi, n_bins, endpoint=False)
    r_prof = np.zeros(n_bins)
    for i in range(n_bins):
        diff = np.angle(np.exp(1j * (angles - theta_grid[i])))
        sel = np.abs(diff) < (2.0 * math.pi / n_bins) * 1.5
        r_prof[i] = float(np.median(radii[sel])) if np.any(sel) else np.nan
    valid = ~np.isnan(r_prof)
    r_prof = np.interp(theta_grid, theta_grid[valid], r_prof[valid])

    r_smooth = ndi.gaussian_filter1d(r_prof, sigma=2.2, mode="wrap")
    r_base = ndi.gaussian_filter1d(r_smooth, sigma=18.0, mode="wrap")
    delta_r = r_base - r_smooth  # Positive at inward-protruding mucosal fold crests

    peaks, _ = signal.find_peaks(delta_r, distance=13, prominence=3.5)
    contour_x = cx + r_smooth * np.cos(theta_grid)
    contour_y = cy + r_smooth * np.sin(theta_grid)
    peak_xy = np.column_stack([contour_x[peaks], contour_y[peaks]])

    area_px2 = float(lumen.sum())
    dx = np.diff(np.append(contour_x, contour_x[0]))
    dy = np.diff(np.append(contour_y, contour_y[0]))
    perim_px = float(np.sum(np.hypot(dx, dy)))
    circularity = float(4.0 * math.pi * area_px2 / max(perim_px**2, 1e-6))

    return {
        "rgb_roi": roi,
        "lumen_mask": lumen,
        "centroid_xy": (cx, cy),
        "contour_x": contour_x,
        "contour_y": contour_y,
        "peak_xy": peak_xy,
        "m_obs_specimen": int(len(peaks)),
        "lumen_area_px2": area_px2,
        "lumen_perimeter_px": perim_px,
        "lumen_circularity": circularity,
        "mean_fold_intrusion_px": float(np.mean(delta_r[peaks])),
    }


