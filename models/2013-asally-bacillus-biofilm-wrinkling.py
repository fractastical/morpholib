# 2. Governing Föppl–von Kármán & Cell-Death Delamination Mechanics
# =============================================================================
def compute_fvk_wavelength_and_strain(
    h_um: float = 80.0,
    E_f_kPa: float = 25.0,
    E_s_kPa: float = 2.5,
    nu_f: float = 0.45,
    nu_s: float = 0.45,
    R_ring_um: float = 1600.0,
    epsilon_g: float = 0.22,
    phi_dead: float = 1.0,
    gamma_d: float = 0.65,
) -> dict[str, float]:
    """
    Compute Föppl–von Kármán bilayer wrinkling invariants and cell-death delamination
    threshold (Asally et al. 2012 PNAS; Trejo et al. 2013 PNAS; Yan et al. 2019 Nat Phys).

    Matches Lean 4 Theorems 1-3 in `Loop_094_bacillus_biofilm_wrinkling.lean`.
    """
    E_bar_f = E_f_kPa / (1.0 - nu_f * nu_f)
    E_bar_s = E_s_kPa / (1.0 - nu_s * nu_s)
    modulus_ratio = E_bar_f / (3.0 * E_bar_s)
    cube_root_ratio = modulus_ratio ** (1.0 / 3.0)

    # Characteristic FvK wavelength lambda_c = 2*pi*h*(E_bar_f / (3*E_bar_s))^(1/3)
    lambda_c_um = float(2.0 * np.pi * h_um * cube_root_ratio)
    q_c_inv_um = float(2.0 * np.pi / lambda_c_um)

    # Critical compressive strain on intact foundation: epsilon_c = 0.25*(3*E_bar_s/E_bar_f)^(2/3)
    epsilon_c_intact = float(0.25 * ((3.0 * E_bar_s / E_bar_f) ** (2.0 / 3.0)))

    # Localized cell-death adhesion degradation lowers effective buckling strain threshold
    epsilon_c_eff = float(epsilon_c_intact * (1.0 - gamma_d * np.clip(phi_dead, 0.0, 1.0)))
    strain_excess = float(max(0.0, epsilon_g - epsilon_c_eff))

    # In-plane biaxial compressive stress sigma_0 = (E_f / (1 - nu_f)) * epsilon_g
    sigma_0_kPa = float((E_f_kPa / (1.0 - nu_f)) * epsilon_g)

    # Bending rigidity D_f = E_bar_f * h^3 / 12
    D_f_kPa_um3 = float(E_bar_f * (h_um ** 3) / 12.0)

    # Radial spoke number around central concentric ring R_ring
    n_spokes_cont = float((2.0 * np.pi * R_ring_um) / lambda_c_um)
    n_spokes_int = int(round(n_spokes_cont)) if strain_excess > 0.0 else 0

    return {
        "h_um": float(h_um),
        "E_f_kPa": float(E_f_kPa),
        "E_s_kPa": float(E_s_kPa),
        "E_bar_f_kPa": float(E_bar_f),
        "E_bar_s_kPa": float(E_bar_s),
        "D_f_kPa_um3": D_f_kPa_um3,
        "sigma_0_kPa": sigma_0_kPa,
        "lambda_c_um": lambda_c_um,
        "q_c_inv_um": q_c_inv_um,
        "epsilon_c_intact": epsilon_c_intact,
        "epsilon_c_eff": epsilon_c_eff,
        "strain_excess": strain_excess,
        "N_spokes_continuous": n_spokes_cont,
        "N_spokes_int": n_spokes_int,
    }


