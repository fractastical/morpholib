# 5. Computer-Vision Segmentation of Vendored Bacillus subtilis Biofilm Specimen
# =============================================================================
def segment_bacillus_biofilm_specimen(ref: dict[str, Any] | None = None) -> dict[str, Any]:
    """
    Segment the SHA-256-locked CC BY-SA 3.0 Bacillus subtilis macrocolony biofilm specimen
    (`datasets/bacillus_biofilm_wrinkling/bacillus_biofilm_specimen.jpg`) to extract:
      1. Isolated circular macrocolonies across the agar plate (n = 11 isolated colonies)
      2. Radial wrinkle spoke ridges around the focal macrocolony at (866.0, 700.6)
         via Difference-of-Gaussians (DoG) ridge filtering and circumferential peak detection.
    """
    if ref is None:
        ref = load_reference_data()
    spec_meta = ref["metadata"]["specimens"]["bacillus_biofilm_specimen"]
    img_rgb = (
        np.asarray(Image.open(SPECIMEN_PATH).convert("RGB"), dtype=np.float64) / 255.0
    )
    gray = 0.299 * img_rgb[:, :, 0] + 0.587 * img_rgb[:, :, 1] + 0.114 * img_rgb[:, :, 2]
    H, W = gray.shape

    # Segment isolated macrocolonies via local background subtraction
    bg = ndimage.gaussian_filter(gray, sigma=65.0)
    mask = (gray - bg) > 0.045
    mask = ndimage.binary_opening(mask, structure=np.ones((5, 5)))
    mask = ndimage.binary_fill_holes(mask)
    labeled, _ = ndimage.label(mask)
    objs = ndimage.find_objects(labeled)

    colonies: list[dict[str, float]] = []
    for idx, sl in enumerate(objs, start=1):
        if sl is None:
            continue
        sub = labeled[sl] == idx
        area = int(sub.sum())
        y0, y1 = sl[0].start, sl[0].stop
        x0, x1 = sl[1].start, sl[1].stop
        if area < 3500 or area > 45000:
            continue
        if x0 < 30 or y0 < 30 or x1 > W - 30 or y1 > H - 30:
            continue
        cy, cx = ndimage.center_of_mass(sub)
        cy += y0
        cx += x0
        r_eq = float(np.sqrt(area / np.pi))
        aspect = float(y1 - y0) / max(1.0, float(x1 - x0))
        if 0.72 <= aspect <= 1.38:
            colonies.append({
                "area_px": float(area),
                "cx_px": float(cx),
                "cy_px": float(cy),
                "r_eq_px": r_eq,
            })

    # Extract circumferential radial spoke ridges on focal macrocolony
    fcx, fcy = spec_meta["focal_colony_center_xy"]
    fr_eq = float(spec_meta["focal_colony_radius_px"])
    ridge_img = ndimage.gaussian_filter(gray, sigma=1.0) - ndimage.gaussian_filter(gray, sigma=4.5)

    n_theta = 360
    thetas = np.linspace(0.0, 2.0 * np.pi, n_theta, endpoint=False)
    radii = np.linspace(0.42 * fr_eq, 0.88 * fr_eq, 20)
    prof = np.zeros(n_theta, dtype=np.float64)
    for r in radii:
        xs = np.clip(np.round(fcx + r * np.cos(thetas)).astype(int), 0, W - 1)
        ys = np.clip(np.round(fcy + r * np.sin(thetas)).astype(int), 0, H - 1)
        prof += ridge_img[ys, xs]
    prof /= float(len(radii))

    prof_pad = np.concatenate([prof[-20:], prof, prof[:20]])
    prof_smooth = ndimage.gaussian_filter1d(prof_pad, sigma=3.0)[20:-20]
    peaks, _ = signal.find_peaks(prof_smooth, distance=18, prominence=0.0010)
    peak_angles_rad = thetas[peaks]
    spacings_rad = np.diff(np.append(peak_angles_rad, peak_angles_rad[0] + 2.0 * np.pi))
    spacing_cv = float(np.std(spacings_rad) / np.mean(spacings_rad))
    mean_angle_deg = float(np.degrees(np.mean(spacings_rad)))

    return {
        "img_rgb": img_rgb,
        "ridge_img": ridge_img,
        "colonies": colonies,
        "n_isolated_colonies": len(colonies),
        "focal_cx": float(fcx),
        "focal_cy": float(fcy),
        "focal_r_px": fr_eq,
        "roi_box_xyxy": spec_meta["roi_box_xyxy"],
        "thetas_deg": np.degrees(thetas),
        "angular_ridge_profile": prof_smooth,
        "peak_indices": peaks,
        "peak_angles_rad": peak_angles_rad,
        "n_spokes_specimen": int(len(peaks)),
        "mean_spoke_angle_deg": mean_angle_deg,
        "spoke_spacing_cv": spacing_cv,
    }


