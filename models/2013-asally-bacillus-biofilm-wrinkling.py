# 8. Comprehensive 8-Point Self-Test Suite (`--self-test`)
# =============================================================================
def self_test() -> None:
    print("[self-test] Running 8-point verification suite for 2013-asally-bacillus-biofilm-wrinkling.py...")
    ref = load_reference_data()

    # 1. Runtime SHA-256 dataset verification
    digests = verify_dataset_integrity(ref)
    assert len(digests) == 4, f"Expected 4 verified dataset digests, got {len(digests)}"

    # 2. FvK wavelength & critical strain scaling invariants
    agar_sweep = evaluate_agar_stiffness_sweep(ref, grid_n=72)
    assert len(agar_sweep["rows"]) == 7, "Expected 7 agar stiffness points"
    assert agar_sweep["pearson_r_lambda"] > 0.999, f"Expected r > 0.999, got {agar_sweep['pearson_r_lambda']}"
    assert abs(agar_sweep["loglog_slope_Es"] - (-1.0 / 3.0)) < 0.015, (
        f"Expected cube-root scaling slope ~ -0.3333, got {agar_sweep['loglog_slope_Es']}"
    )

    # 3. Biofilm thickness scaling invariants
    thick_sweep = evaluate_thickness_scaling_sweep(ref, grid_n=72)
    assert len(thick_sweep["rows"]) == 6, "Expected 6 thickness scaling points"
    assert thick_sweep["pearson_r_thickness"] > 0.999, "Expected r > 0.999 for thickness scaling"
    assert abs(thick_sweep["loglog_slope_h"] - 1.0) < 0.015, "Expected linear wavelength scaling with h"

    # 4. Wild-type vs Delta eps/tasA mutant & cell-death suppression controls
    controls = evaluate_genetic_and_mechanical_controls(ref, grid_n=72)
    assert controls["wild_type_ncib3610"]["N_spokes_sim"] == 13, "WT must form 13 radial spokes"
    assert controls["wild_type_ncib3610"]["amplitude_sim_um"] > 150.0, "WT amplitude must exceed 150 um"
    assert controls["delta_eps_tasA_mutant"]["amplitude_sim_um"] == 0.0, "Delta eps/tasA mutant must remain flat"
    assert controls["cell_death_suppressed_fe_overload"]["amplitude_sim_um"] == 0.0, (
        "Cell-death-suppressed colony must remain flat below intact threshold"
    )

    # 5. Artificial mechanical-score pattern guidance (m = 6 and m = 8)
    assert controls["artificial_score_6_spokes"]["N_spokes_sim"] == 6, "Guided m=6 template must produce 6 spokes"
    assert controls["artificial_score_8_spokes"]["N_spokes_sim"] == 8, "Guided m=8 template must produce 8 spokes"

    # 6. Specimen segmentation invariants
    specimen = segment_bacillus_biofilm_specimen(ref)
    assert specimen["n_isolated_colonies"] >= 8, "Expected >= 8 isolated macrocolonies on specimen plate"
    assert 10 <= specimen["n_spokes_specimen"] <= 15, (
        f"Expected 10-15 radial spokes on focal colony, got {specimen['n_spokes_specimen']}"
    )

    # 7. Bitwise determinism check across two independent runs
    run1 = relax_fvk_biofilm_colony(grid_n=64, seed=2013)
    run2 = relax_fvk_biofilm_colony(grid_n=64, seed=2013)
    assert np.allclose(run1["w_um"], run2["w_um"], atol=0.0), "2D FvK energy minimizer must be bitwise deterministic"

    # 8. MorphoEval measurement contract check
    metrics = measure_morphoeval()
    assert len(metrics) == 9, f"Expected 9 morphometric measurements, got {len(metrics)}"
    print("[self-test] All 8 verification checks PASSED (SHA-256, FvK E_s^-1/3 & h^1 scaling, mutant controls, CV specimen, bitwise determinism).")


