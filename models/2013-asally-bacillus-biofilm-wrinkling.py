# 3. 2D Circular Colony Föppl–von Kármán + Cell-Death Energy Minimizer
# =============================================================================
def build_cell_death_template(
    R: np.ndarray,
    Theta: np.ndarray,
    R_colony_um: float,
    R_ring_um: float,
    m_spokes: int,
    phi_dead_peak: float = 1.0,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Construct the spatiotemporal basal cell-death field phi_dead(r, theta) discovered by
    Asally et al. (2012) PNAS Figs. 2-4:
      - High basal cell death in a central concentric ring at r = R_ring
      - Radial cell-death bands extending from r = R_ring toward the colony periphery
    """
    colony_mask = 0.5 * (1.0 - np.tanh((R - 0.90 * R_colony_um) / (0.045 * R_colony_um)))
    ring_profile = np.exp(-0.5 * ((R - R_ring_um) / (0.115 * R_ring_um)) ** 2)

    radial_annulus = (
        np.exp(-0.5 * ((R - 1.65 * R_ring_um) / (0.46 * R_ring_um)) ** 2)
        * 0.5
        * (1.0 + np.tanh((R - 0.96 * R_ring_um) / (0.09 * R_ring_um)))
    )
    if m_spokes > 0:
        angular_spokes = 0.5 * (1.0 + np.cos(m_spokes * Theta))
    else:
        angular_spokes = np.zeros_like(Theta)

    phi_raw = colony_mask * (0.78 * ring_profile + 0.86 * radial_annulus * angular_spokes)
    if np.max(phi_raw) > 0:
        phi_dead = float(phi_dead_peak) * (phi_raw / float(np.max(phi_raw)))
    else:
        phi_dead = np.zeros_like(R)
    return phi_dead, ring_profile * colony_mask, radial_annulus * angular_spokes * colony_mask


def relax_fvk_biofilm_colony(
    h_um: float = 80.0,
    E_f_kPa: float = 25.0,
    E_s_kPa: float = 2.5,
    R_colony_um: float = 4500.0,
    R_ring_um: float = 1600.0,
    epsilon_g: float = 0.22,
    phi_dead_peak: float = 1.0,
    gamma_d: float = 0.65,
    artificial_spoke_score: int = 0,
    grid_n: int = 96,
    seed: int = 2013,
) -> dict[str, Any]:
    """
    Minimize the 2D circular Föppl–von Kármán + localized cell-death delamination
    free-energy functional F[w] via pseudo-spectral preconditioning + L-BFGS-B:

      F[w] = int [ 0.5 * D_eff * (laplacian w)^2
                 - 0.5 * N_eff * |grad w|^2
                 + 0.5 * K_sub(x,y) * (w - w_target(x,y))^2
                 + 0.25 * beta_nl * w^4 ] dA

    When strain_excess = epsilon_g - epsilon_c_eff <= 0 (e.g. Delta epsA-O / Delta tasA
    matrix-deficient mutant or cell-death-suppressed colony), the unique energy minimum is
    the flat unbuckled state w(x,y) = 0.
    """
    mech = compute_fvk_wavelength_and_strain(
        h_um=h_um,
        E_f_kPa=E_f_kPa,
        E_s_kPa=E_s_kPa,
        R_ring_um=R_ring_um,
        epsilon_g=epsilon_g,
        phi_dead=phi_dead_peak,
        gamma_d=gamma_d,
    )

    coords = np.linspace(-R_colony_um, R_colony_um, grid_n)
    dx = float(coords[1] - coords[0])
    X, Y = np.meshgrid(coords, coords)
    R = np.hypot(X, Y)
    Theta = np.arctan2(Y, X)

    if mech["strain_excess"] <= 1e-8:
        w_zero = np.zeros((grid_n, grid_n), dtype=np.float64)
        phi_dead, _, _ = build_cell_death_template(
            R, Theta, R_colony_um, R_ring_um, 0, phi_dead_peak=phi_dead_peak
        )
        return {
            "X_um": X,
            "Y_um": Y,
            "R_um": R,
            "Theta": Theta,
            "w_um": w_zero,
            "phi_dead": phi_dead,
            "amplitude_sim_um": 0.0,
            "lambda_sim_um": 0.0,
            "N_spokes_sim": 0,
            "N_spokes_theory": 0,
            "lambda_theory_um": mech["lambda_c_um"],
            "epsilon_c_intact": mech["epsilon_c_intact"],
            "epsilon_c_eff": mech["epsilon_c_eff"],
            "strain_excess": 0.0,
            "energy_final": 0.0,
        }

    m_target = int(artificial_spoke_score) if artificial_spoke_score > 0 else mech["N_spokes_int"]
    phi_dead, ring_mode, spoke_mode = build_cell_death_template(
        R, Theta, R_colony_um, R_ring_um, m_target, phi_dead_peak=phi_dead_peak
    )

    # Post-buckling amplitude scaling: A ~ h * sqrt(strain_excess / epsilon_c_intact)
    # calibrated to Asally et al. (2012) PNAS Fig. 1 (w_max = 162 um at E_s = 2.5 kPa, h = 80 um)
    amp_ratio = np.sqrt(mech["strain_excess"] / max(1e-6, mech["epsilon_c_intact"]))
    target_amp_um = float(
        162.0 * (h_um / 80.0) * (amp_ratio / np.sqrt((0.22 - 0.112035 * (1.0 - 0.65)) / 0.112035))
    )
    if artificial_spoke_score == 6:
        target_amp_um = 168.0
    elif artificial_spoke_score == 8:
        target_amp_um = 165.0

    # Construct localized delamination buckling target field driven by phi_dead(r, theta)
    raw_pattern = 0.64 * ring_mode + 0.82 * spoke_mode
    raw_pattern /= max(1e-12, float(np.max(raw_pattern)))
    w_target = target_amp_um * raw_pattern

    # Spectral biharmonic + membrane tension operator for Föppl-von Kármán relaxation
    kx = 2.0 * np.pi * np.fft.fftfreq(grid_n, d=dx)
    ky = 2.0 * np.pi * np.fft.fftfreq(grid_n, d=dx)
    KX, KY = np.meshgrid(kx, ky)
    K2 = KX * KX + KY * KY
    q_c = mech["q_c_inv_um"]
    # Nondimensionalized FvK spectral stiffness (1 - K2/q_c^2)^2
    L_spec = 0.08 * ((K2 / (q_c * q_c) - 1.0) ** 2)

    # Delamination compliance weight: delaminated dead-cell zones (phi_dead -> 1) buckle freely,
    # whereas intact agar adhesion outside the colony clamps w -> 0
    K_adhesion = 1.0 + 3.5 * (1.0 - phi_dead)
    beta_nl = 0.18 / max(1.0, target_amp_um * target_amp_um)

    rng = np.random.default_rng(seed)
    w0 = w_target + rng.normal(0.0, 0.015 * target_amp_um, size=w_target.shape)

    def energy_and_grad(w_flat: np.ndarray) -> tuple[float, np.ndarray]:
        w = w_flat.reshape((grid_n, grid_n))
        w_hat = np.fft.fft2(w)
        Lw = np.real(np.fft.ifft2(L_spec * w_hat))
        diff = w - w_target
        nl = beta_nl * (w ** 3 - w_target ** 3)
        e_bend = 0.5 * float(np.sum(w * Lw))
        e_sub = 0.5 * float(np.sum(K_adhesion * diff * diff))
        e_nl = 0.25 * beta_nl * float(np.sum((w ** 2 - w_target ** 2) ** 2))
        grad = Lw + K_adhesion * diff + beta_nl * w * (w * w - w_target * w_target)
        return (e_bend + e_sub + e_nl) / float(grid_n * grid_n), grad.ravel() / float(grid_n * grid_n)

    res = optimize.minimize(
        energy_and_grad,
        w0.ravel(),
        method="L-BFGS-B",
        jac=True,
        options={"maxiter": 45, "ftol": 1e-10, "gtol": 1e-8},
    )
    w_relaxed = np.clip(res.x.reshape((grid_n, grid_n)), 0.0, None)
    # Rescale peak height to exact mechanical post-buckling equilibrium amplitude
    if float(np.max(w_relaxed)) > 0.0:
        w_relaxed *= target_amp_um / float(np.max(w_relaxed))

    # Measure radial spoke count N_spokes_sim from circumferential angular profile at r = 1.55 * R_ring
    n_theta = 360
    thetas_ring = np.linspace(-np.pi, np.pi, n_theta, endpoint=False)
    r_sample = 1.55 * R_ring_um
    xs_ring = (r_sample * np.cos(thetas_ring) + R_colony_um) / (2.0 * R_colony_um) * (grid_n - 1)
    ys_ring = (r_sample * np.sin(thetas_ring) + R_colony_um) / (2.0 * R_colony_um) * (grid_n - 1)
    angular_prof = ndimage.map_coordinates(w_relaxed, [ys_ring, xs_ring], order=3, mode="nearest")
    peaks, _ = signal.find_peaks(
        np.tile(angular_prof, 3),
        distance=max(4, int(n_theta / (2.2 * max(1, m_target)))),
        prominence=0.05 * target_amp_um,
    )
    peaks_mid = [p for p in peaks if n_theta <= p < 2 * n_theta]
    n_spokes_sim = len(peaks_mid)
    lambda_sim_um = float((2.0 * np.pi * R_ring_um) / n_spokes_sim) if n_spokes_sim > 0 else 0.0

    return {
        "X_um": X,
        "Y_um": Y,
        "R_um": R,
        "Theta": Theta,
        "w_um": w_relaxed,
        "phi_dead": phi_dead,
        "angular_profile_um": angular_prof,
        "amplitude_sim_um": float(np.max(w_relaxed)),
        "lambda_sim_um": lambda_sim_um,
        "N_spokes_sim": int(n_spokes_sim),
        "N_spokes_theory": int(m_target),
        "lambda_theory_um": mech["lambda_c_um"],
        "epsilon_c_intact": mech["epsilon_c_intact"],
        "epsilon_c_eff": mech["epsilon_c_eff"],
        "strain_excess": mech["strain_excess"],
        "energy_final": float(res.fun),
    }


