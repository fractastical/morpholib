# --------------------------------------------------------------------------- model (E1-E4)
def log_spiral(theta, a, k):
    """E1: rho = a exp(k theta)."""
    return a * np.exp(k * np.asarray(theta, float))


def k_from_alpha(alpha_deg, beta_deg=90.0):
    """E2: k = sin(beta) cot(alpha) (beta = 90 deg -> plane spiral)."""
    return math.sin(math.radians(beta_deg)) / math.tan(math.radians(alpha_deg))


def alpha_from_k(k, beta_deg=90.0):
    return math.degrees(math.atan2(math.sin(math.radians(beta_deg)), k))


def whorl_ratio(alpha_deg, beta_deg=90.0):
    """E3: R = exp(2 pi sin(beta) cot(alpha))."""
    return math.exp(2 * math.pi * k_from_alpha(alpha_deg, beta_deg))


def helico_spiral(theta, a, alpha_deg, beta_deg):
    """E2 in Cartesian coordinates: a logarithmic spiral wound on a cone of semi-angle beta."""
    rho = log_spiral(theta, a, k_from_alpha(alpha_deg, beta_deg))
    z = rho / math.tan(math.radians(beta_deg)) if beta_deg < 90 else np.zeros_like(rho)
    return rho * np.cos(theta), rho * np.sin(theta), z


def horn_surface(theta_max, a=1.0, alpha_deg=75.0, beta_deg=60.0, breadth_ratio=0.35,
                 n_theta=160, n_phi=24):
    """Gnomonic horn: tube of radius breadth_ratio * rho(theta) swept along the helico-spiral (E2 + E4)."""
    th = np.linspace(0, theta_max, n_theta)
    cx, cy, cz = helico_spiral(th, a, alpha_deg, beta_deg)
    centre = np.stack([cx, cy, cz], 1)
    tang = np.gradient(centre, axis=0)
    tang /= np.linalg.norm(tang, axis=1, keepdims=True) + 1e-12
    ref = np.array([0.0, 0.0, 1.0])
    n1 = np.cross(tang, ref)
    bad = np.linalg.norm(n1, axis=1) < 1e-6
    n1[bad] = np.cross(tang[bad], np.array([1.0, 0.0, 0.0]))
    n1 /= np.linalg.norm(n1, axis=1, keepdims=True)
    n2 = np.cross(tang, n1)
    rho = np.hypot(cx, cy)
    r_tube = breadth_ratio * rho / 2.0
    phi = np.linspace(0, 2 * np.pi, n_phi)
    X = centre[:, None, 0] + r_tube[:, None] * (np.cos(phi)[None] * n1[:, None, 0] + np.sin(phi)[None] * n2[:, None, 0])
    Y = centre[:, None, 1] + r_tube[:, None] * (np.cos(phi)[None] * n1[:, None, 1] + np.sin(phi)[None] * n2[:, None, 1])
    Z = centre[:, None, 2] + r_tube[:, None] * (np.cos(phi)[None] * n1[:, None, 2] + np.sin(phi)[None] * n2[:, None, 2])
    return X, Y, Z


# --------------------------------------------------------------------------- data access
def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def load_reference() -> dict:
    return json.loads(REF_JSON.read_text())


def verify_inputs(ref: dict) -> dict:
    out = {}
    for name, digest in ref["input_dataset_sha256"].items():
        p = DATA / name
        actual = sha256_file(p) if p.exists() else None
        out[name] = {"expected": digest, "actual": actual, "ok": actual == digest}
    return out


def load_gray(path: Path) -> np.ndarray:
    from PIL import Image
    return np.asarray(Image.open(path).convert("L")).astype(float) / 255.0


# --------------------------------------------------------------------------- segmentation
def segment_figure_ink(gray: np.ndarray, ink_threshold: float) -> np.ndarray:
    """Thompson line drawing -> filled silhouette of everything enclosed by ink (largest component)."""
    from scipy import ndimage as ndi
    from skimage import measure, morphology
    ink = gray < ink_threshold
    ink = morphology.closing(ink, morphology.disk(2))
    sil = ndi.binary_fill_holes(ink)
    lab = measure.label(sil)
    props = measure.regionprops(lab)
    big = max(props, key=lambda p: p.area)
    return lab == big.label


def silhouette_contour(mask: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    from skimage import measure
    cs = measure.find_contours(mask.astype(float), 0.5)
    c = max(cs, key=len)
    return c[:, 1], c[:, 0]  # x, y


def math_angle_deg(x, y, cx, cy):
    """Polar angle in the mathematical convention (x right, y up) for image coords (y down)."""
    return np.degrees(np.arctan2(-(np.asarray(y) - cy), np.asarray(x) - cx))


def outer_edge_points(xs, ys, pole_guess, sector_deg, n_bins=720):
    """Farthest contour point per angular bin inside [sector_lo, sector_hi] (math degrees)."""
    cx, cy = pole_guess
    th = math_angle_deg(xs, ys, cx, cy)
    rho = np.hypot(xs - cx, ys - cy)
    bins = np.floor((th + 180.0) / 360.0 * n_bins).astype(int) % n_bins
    lo, hi = sector_deg
    sel = []
    for b in range(n_bins):
        idx = np.where(bins == b)[0]
        if len(idx) == 0:
            continue
        i = idx[np.argmax(rho[idx])]
        if lo <= th[i] <= hi:
            sel.append(i)
    sel = np.array(sel, int)
    return xs[sel], ys[sel]


# --------------------------------------------------------------------------- fitting
def growth_angle(px, py, cx, cy):
    """Growth parameter t (radians) increasing clockwise in image space from the tip end (t = 0)."""
    t = np.unwrap(-np.radians(math_angle_deg(px, py, cx, cy)))
    return t - t.min()


def fit_log_spiral(px, py, pole_guess, k0=0.25):
    """E1 with free pole: minimise sum (rho_i - a exp(k t_i))^2 over (cx, cy, ln a, k)."""
    from scipy.optimize import least_squares

    def resid(p):
        cx, cy, lna, k = p
        t = growth_angle(px, py, cx, cy)
        r = np.hypot(px - cx, py - cy)
        return r - np.exp(lna + k * t)

    gx, gy = pole_guess
    span = 0.25 * max(np.ptp(px), np.ptp(py))
    best = None
    for dx in np.linspace(-span, span, 5):
        for dy in np.linspace(-span, span, 5):
            r0 = np.hypot(px - (gx + dx), py - (gy + dy)).mean()
            try:
                sol = least_squares(resid, [gx + dx, gy + dy, math.log(r0), k0], max_nfev=400)
            except Exception:
                continue
            if best is None or sol.cost < best.cost:
                best = sol
    cx, cy, lna, k = best.x
    t = growth_angle(px, py, cx, cy)
    r = np.hypot(px - cx, py - cy)
    res = best.fun
    # t runs clockwise in image space; the sign of k only records which way the horn
    # opens in this view, so alpha and the whorl ratio are taken from |k|.
    return {
        "model": "log_spiral", "cx": float(cx), "cy": float(cy), "a": float(math.exp(lna)), "k": float(k),
        "k_abs": float(abs(k)), "rho_increases": "clockwise" if k >= 0 else "counterclockwise",
        "alpha_deg": float(alpha_from_k(abs(k))), "whorl_ratio": float(math.exp(2 * math.pi * abs(k))),
        "sweep_deg": float(math.degrees(t.max())), "n": int(len(px)),
        "rmse_px": float(np.sqrt(np.mean(res ** 2))), "rss": float(np.sum(res ** 2)),
        "rmse_rel": float(np.sqrt(np.mean(res ** 2)) / r.mean()),
        "pearson_r_lnrho_theta": float(abs(np.corrcoef(t, np.log(r))[0, 1])),
        "n_params": 4, "_t": t, "_r": r, "_res": res,
    }


def fit_archimedean(px, py, pole_guess):
    from scipy.optimize import least_squares

    def resid(p):
        cx, cy, a, b = p
        t = growth_angle(px, py, cx, cy)
        return np.hypot(px - cx, py - cy) - (a + b * t)

    gx, gy = pole_guess
    r0 = np.hypot(px - gx, py - gy)
    sol = least_squares(resid, [gx, gy, r0.min(), (r0.max() - r0.min()) / 4.0], max_nfev=400)
    res = sol.fun
    return {"model": "archimedean", "cx": float(sol.x[0]), "cy": float(sol.x[1]), "a": float(sol.x[2]),
            "b": float(sol.x[3]), "rmse_px": float(np.sqrt(np.mean(res ** 2))), "rss": float(np.sum(res ** 2)),
            "n_params": 4, "n": int(len(px))}


def fit_circle(px, py, pole_guess):
    from scipy.optimize import least_squares

    def resid(p):
        cx, cy, a = p
        return np.hypot(px - cx, py - cy) - a

    gx, gy = pole_guess
    sol = least_squares(resid, [gx, gy, np.hypot(px - gx, py - gy).mean()], max_nfev=400)
    res = sol.fun
    return {"model": "circle", "cx": float(sol.x[0]), "cy": float(sol.x[1]), "radius": float(sol.x[2]),
            "rmse_px": float(np.sqrt(np.mean(res ** 2))), "rss": float(np.sum(res ** 2)), "n_params": 3,
            "n": int(len(px))}


def aic(fit: dict) -> float:
    n = fit["n"]
    return n * math.log(fit["rss"] / n) + 2 * fit["n_params"]


def model_comparison(px, py, pole_guess) -> dict:
    fits = {"log_spiral": fit_log_spiral(px, py, pole_guess),
            "archimedean": fit_archimedean(px, py, pole_guess),
            "circle": fit_circle(px, py, pole_guess)}
    aics = {k: aic(v) for k, v in fits.items()}
    best = min(aics, key=aics.get)
    return {"fits": fits, "aic": aics, "best_by_aic": best,
            "delta_aic_circle_minus_log": aics["circle"] - aics["log_spiral"],
            "delta_aic_archimedean_minus_log": aics["archimedean"] - aics["log_spiral"]}


def public(fit: dict) -> dict:
    return {k: v for k, v in fit.items() if not k.startswith("_")}


# --------------------------------------------------------------------------- specimen pipeline
def analyse_specimen(spec: dict) -> dict:
    gray = load_gray(DATA / spec["file"])
    seg = spec["segmentation"]
    if seg["mode"] != "figure_ink":
        raise NotImplementedError(f"Pass 1 handles figure_ink only (got {seg['mode']})")
    mask = segment_figure_ink(gray, seg["ink_threshold"])
    xs, ys = silhouette_contour(mask)
    px, py = outer_edge_points(xs, ys, spec["pole_guess_px"], spec["outer_edge_sector_deg"])
    cmp = model_comparison(px, py, spec["pole_guess_px"])
    ls = cmp["fits"]["log_spiral"]
    return {
        "id": spec["id"], "species": spec["species"], "kind": spec["kind"], "file": spec["file"],
        "n_edge_points": int(len(px)), "image_shape": list(gray.shape),
        "log_spiral": public(ls), "archimedean": cmp["fits"]["archimedean"], "circle": cmp["fits"]["circle"],
        "aic": cmp["aic"], "best_by_aic": cmp["best_by_aic"],
        "delta_aic_circle_minus_log": cmp["delta_aic_circle_minus_log"],
        "delta_aic_archimedean_minus_log": cmp["delta_aic_archimedean_minus_log"],
        "alpha_minus_thompson_deg": float(ls["alpha_deg"] - THOMPSON_ALPHA_OVIS_AMMON),
        "_gray": gray, "_mask": mask, "_px": px, "_py": py, "_ls": ls,
    }


