#!/usr/bin/env python3
"""
Validate predictions/live_arguments.json and render its summary.

Every entry must satisfy the selection rule declared in the file: >=2 camps,
>=1 repo dataset that exists on disk, genome tier A/B (never D), a named
settling measurement, and a candidate prediction that is NOT yet registered
(candidates become registered predictions only after Delphi scoring, per
the record-a-probability-before-acting rule). A map entry that fails any of
these is exactly the failure mode this file exists to prevent: a vague
'interesting question' dressed as a decidable argument.

Usage:
  python3 predictions/check_live_arguments.py            # validate + summary
  python3 predictions/check_live_arguments.py --write    # also write live_arguments_summary.md
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
REG = HERE / "live_arguments.json"
SUMMARY = HERE / "live_arguments_summary.md"


def check(data: dict) -> list[str]:
    errs = []
    ids = set()
    for a in data.get("arguments", []):
        aid = a.get("id", "?")
        if aid in ids:
            errs.append(f"{aid}: duplicate id")
        ids.add(aid)
        if len(a.get("camps", [])) < 2:
            errs.append(f"{aid}: needs >=2 camps to be a live argument")
        for c in a.get("camps", []):
            if not all(c.get(k) for k in ("side", "claim", "representative_evidence")):
                errs.append(f"{aid}: camp missing side/claim/representative_evidence: {c.get('side')}")
        if not a.get("related_datasets"):
            errs.append(f"{aid}: no related datasets")
        for ds in a.get("related_datasets", []):
            if not (ROOT / ds).exists():
                errs.append(f"{aid}: dataset not on disk: {ds}")
        tier = a.get("species", {}).get("genome_tier", "")
        if not tier.startswith(("A", "B", "C")):
            errs.append(f"{aid}: genome tier must be A/B/C (D is excluded), got {tier!r}")
        if not a.get("settling_measurement"):
            errs.append(f"{aid}: no settling measurement named")
        cp = a.get("candidate_prediction", {})
        if cp.get("status") != "candidate_not_registered":
            errs.append(f"{aid}: candidate must stay candidate_not_registered until Delphi-scored + registered")
        if not (0 < cp.get("proposed_resolvability_confidence", 0) < 1):
            errs.append(f"{aid}: proposed_resolvability_confidence must be in (0,1)")
        if not cp.get("falsifier"):
            errs.append(f"{aid}: candidate prediction has no falsifier")
        if a.get("argument_status") not in ("live", "partly_settled"):
            errs.append(f"{aid}: argument_status must be live|partly_settled")
        if a.get("argument_status") == "partly_settled" and not a.get("settled_part"):
            errs.append(f"{aid}: partly_settled must state which part is settled (never re-litigate it)")
    return errs


def render_summary(data: dict) -> str:
    rows = []
    for a in data["arguments"]:
        cp = a["candidate_prediction"]
        rows.append(
            f"| {a['id']} | {a['question'][:110]}… | {a['argument_status']} | "
            f"{len(a['camps'])} | {len(a['related_datasets'])} | {a['species']['genome_tier']} | "
            f"{cp['proposed_resolvability_confidence']:.2f} | {a['priority']['decidability']} |")
    return f"""# Live arguments mapped to datasets

Generated by `predictions/check_live_arguments.py --write` from
`predictions/live_arguments.json` — regenerate, do not hand-edit this table.

Each row is a contested question in the literature (≥2 camps in print),
mapped to repo datasets that bear on it, the genome tier of the species,
and the measurement that would settle it. An entry is a **candidate**, not
a finding: promotion is Delphi-score the probability → register the
prediction → score it against public records → resolution record → nanopub.

| ID | Question | Status | Camps | Datasets | Tier | Proposed resolvability | Decidability |
|---|---|---|---|---|---|---|---|
{chr(10).join(rows)}

Top-ranked by decidability-to-contestation: **LA-06** (Dpp gradient
scaling, Drosophila — core kinetics already public, 621 fly datasets).
LA-01's settled half (free-diffusion refuted, ZF-TUR-01) must not be
re-litigated; only its scaling remainder is live. LA-07 (bioelectric
prepattern) is included with the repo's own negative blind-test history
stated, and requires an experimental collaborator, not literature scoring.
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Validate the live-arguments map")
    ap.add_argument("--write", action="store_true", help="write live_arguments_summary.md")
    args = ap.parse_args(argv)
    data = json.loads(REG.read_text())
    errs = check(data)
    if errs:
        print("REFUSING — live-arguments map failed checks:")
        for e in errs:
            print(f" - {e}")
        return 1
    n = len(data["arguments"])
    print(f"[PASS] {n} live arguments: >=2 camps each, all datasets on disk, "
          f"tiers A-C only, every candidate unregistered with a falsifier")
    for a in data["arguments"]:
        print(f"  {a['id']}  {a['argument_status']:15s} camps={len(a['camps'])} "
              f"datasets={len(a['related_datasets'])} tier={a['species']['genome_tier']} "
              f"conf={a['candidate_prediction']['proposed_resolvability_confidence']}")
    if args.write:
        SUMMARY.write_text(render_summary(data))
        print(f"Wrote {SUMMARY}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
