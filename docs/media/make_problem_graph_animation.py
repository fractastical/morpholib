#!/usr/bin/env python3
"""Animated summary of the discovery problem graph.

    python3 docs/media/make_problem_graph_animation.py
        # -> docs/media/problem_graph_discovery.gif
        # -> docs/media/problem_graph_discovery_poster.png

Source of truth is the *built* graph page (docs/problem-graph.html, itself
generated by docs/build_problem_graph_html.py from the canvas + registries):
this script parses the embedded DATA / PRED / THOMP literals and the
MorphoSwarm feed (docs/open-problems.json) out of it, so every number on
screen is recomputed from the graph -- never hand-typed. Storyboard:

  1. Title     -- the question, headline counts
  2. Build     -- all nodes appear lane by lane, edges = recorded attempts
  3. Outcomes  -- solved / partial / open / refuted sweep (pruned = kept)
  4. Zoom      -- registered predictions (outcome + resolvability, scored)
  5. Finale    -- scientific claims shown definitively, positively or negatively
                  (audit / infrastructure / agent-process nodes excluded)
"""
from __future__ import annotations

import argparse
import json
import re
import textwrap
from collections import Counter
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, ImageSequence  # noqa: F401  (ImageSequence kept for parity)

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
W, H = 1240, 700
NW, NH = 150, 76  # node size in graph coordinates (matches problem-graph.html)

BG = (247, 247, 245)
INK = (28, 28, 30)
MUT = (92, 92, 96)
LINE = (216, 216, 211)
DARK = (30, 41, 59)
ACCENT = (37, 99, 235)
SCOL = {"solved": (23, 138, 95), "partial": (231, 154, 40), "open": (214, 69, 69),
        "refuted": (126, 42, 58), "registered": (62, 127, 184), "root": (75, 63, 160)}
SLAB = {"solved": "solved / proved", "partial": "partial", "open": "OPEN",
        "refuted": "refuted / pruned", "registered": "registered", "root": "umbrella"}
ACOL = {"human": (232, 192, 48), "fable": (123, 100, 184), "gemini": (46, 121, 181),
        "gpt": (31, 138, 101), "sonnet": (200, 88, 152), "grok": (240, 160, 64),
        "wainwright": (42, 154, 138), "panel": (90, 108, 192),
        "unattributed": (136, 136, 168), "wonder": (14, 124, 123)}


def font(size: int, bold: bool = False):
    import matplotlib
    d = Path(matplotlib.get_data_path()) / "fonts" / "ttf"
    return ImageFont.truetype(str(d / ("DejaVuSans-Bold.ttf" if bold else "DejaVuSans.ttf")), size)


def extract(html: str, name: str):
    i = html.index(f"const {name} = ") + len(f"const {name} = ")
    obj, _ = json.JSONDecoder().raw_decode(html[i:])
    return obj


def load():
    html = (ROOT / "docs" / "problem-graph.html").read_text()
    data = extract(html, "DATA")
    pred = extract(html, "PRED")
    thomp = extract(html, "THOMP")
    swarm = json.loads((ROOT / "docs" / "open-problems.json").read_text())
    return data, pred, thomp, swarm


def smooth(t: float) -> float:
    return t * t * (3 - 2 * t)


def lerp(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(len(a)))


class Graph:
    def __init__(self, data):
        self.nodes = data["NODES"]
        self.edges = data["EDGES"]
        self.by_id = {n["id"]: n for n in self.nodes}
        xs = [n["x"] for n in self.nodes]; ys = [n["y"] for n in self.nodes]
        self.full = (min(xs) - 30, min(ys) - 120, max(xs) + NW + 30, max(ys) + NH + 30)
        # build order: root first, then row by row (y, then x) so the board
        # fills top-to-bottom across all lanes, as it grew chronologically
        self.order = sorted(self.nodes, key=lambda n: (n["status"] != "root", n["y"], n["x"]))
        self.rank = {n["id"]: i for i, n in enumerate(self.order)}

    def view(self, cam, visible: set, focus=None, dim_others=False):
        """Render the graph through camera `cam` = (x0,y0,x1,y1) graph coords."""
        img = Image.new("RGB", (W, H), BG)
        d = ImageDraw.Draw(img)
        x0, y0, x1, y1 = cam
        s = min(W / (x1 - x0), H / (y1 - y0))
        ox, oy = (W - (x1 - x0) * s) / 2, (H - (y1 - y0) * s) / 2

        def pt(x, y):
            return (ox + (x - x0) * s, oy + (y - y0) * s)

        if (x1 - x0) > 1200:  # full view: lane headers, as on the page
            lanes = ["THOMPSON 1917", "MORPHOEVAL", "RULE 30", "PRIZES", "LEVIN", "BIOELECTRIC"]
            for lx, lab in zip((95, 330, 565, 810, 1050, 1290), lanes):
                px, py = pt(lx, min(n["y"] for n in self.nodes) - 28)
                d.text((px, py), lab, font=font(10, True), fill=(136, 136, 132), anchor="ma")
        for e in self.edges:
            a, b = self.by_id.get(e["from"]), self.by_id.get(e["to"])
            if not a or not b or a["id"] not in visible or b["id"] not in visible:
                continue
            dim = dim_others and focus is not None and not (
                self.by_id[e["from"]]["status"] in focus or self.by_id[e["to"]]["status"] in focus)
            col = (205, 205, 200) if dim else ACOL.get(e["agent"], (150, 150, 150))
            x1p, y1p = pt(a["x"] + NW / 2, a["y"] + NH)
            x2p, y2p = pt(b["x"] + NW / 2, b["y"])
            mid = (y1p + y2p) / 2
            pts = []
            for k in range(13):
                t = k / 12
                # cubic bezier, control points straight below/above (as in the SVG)
                px = (1 - t) ** 3 * x1p + 3 * (1 - t) ** 2 * t * x1p + 3 * (1 - t) * t * t * x2p + t ** 3 * x2p
                py = (1 - t) ** 3 * y1p + 3 * (1 - t) ** 2 * t * mid + 3 * (1 - t) * t * t * mid + t ** 3 * y2p
                pts.append((px, py))
            d.line(pts, fill=col, width=max(1, int(2.2 * s)))
        fs = max(6, min(13, int(11 * s)))
        for n in self.nodes:
            if n["id"] not in visible:
                continue
            dim = dim_others and focus is not None and n["status"] not in focus
            x, y = pt(n["x"], n["y"])
            w, h = NW * s, NH * s
            if x + w < 0 or y + h < 0 or x > W or y > H:
                continue
            fill = (238, 238, 235) if dim else ((238, 242, 255) if n["status"] == "root" else (255, 255, 255))
            scol = (200, 200, 195) if dim else SCOL.get(n["status"], (150, 150, 150))
            d.rounded_rectangle([x, y, x + w, y + h], radius=max(2, int(6 * s)),
                                fill=fill, outline=scol, width=max(1, int(1.6 * s)))
            # outcome triangle, top-left (as in the SVG)
            t = max(4, int(11 * s))
            d.polygon([(x + 2, y + 2), (x + t, y + 2), (x + 2, y + t)],
                      fill=(205, 205, 200) if dim else scol)
            if s > 0.42:
                label = n["label"]
                lines = textwrap.wrap(label, width=max(10, int(21 * s)))[:2]
                ty = y + h / 2 - len(lines) * fs / 2
                for ln in lines:
                    d.text(((x + x + w) / 2, ty), ln, font=font(fs, True),
                           fill=(170, 170, 165) if dim else INK, anchor="ma")
                    ty += fs + 1
        return img


def banner(img, title, sub=None):
    d = ImageDraw.Draw(img)
    d.rectangle([0, 0, W, 64], fill=DARK)
    d.text((18, 10), title, font=font(20, True), fill=(255, 255, 255))
    if sub:
        d.text((18, 38), sub, font=font(12), fill=(203, 213, 225))
    return img


def panel(img, box, title, lines, title_col=INK):
    d = ImageDraw.Draw(img)
    d.rounded_rectangle(box, radius=10, fill=(255, 255, 255), outline=LINE, width=2)
    x0, y0 = box[0] + 16, box[1] + 12
    d.text((x0, y0), title, font=font(15, True), fill=title_col)
    y = y0 + 26
    for text, size, col, bold in lines:
        d.text((x0, y), text, font=font(size, bold), fill=col)
        y += size + 7
    return img


def stat_panel(img, box, title, rows, footer=None):
    """rows = (label, value, colour); values right-aligned in their own column."""
    d = ImageDraw.Draw(img)
    d.rounded_rectangle(box, radius=10, fill=(255, 255, 255), outline=LINE, width=2)
    x0, y0, x1 = box[0] + 16, box[1] + 12, box[2] - 16
    d.text((x0, y0), title, font=font(15, True), fill=INK)
    y = y0 + 30
    for lab, val, col in rows:
        d.text((x0, y), lab, font=font(14), fill=INK)
        d.text((x1, y), str(val), font=font(14, True), fill=col, anchor="ra")
        y += 23
    if footer:
        d.text((x0, y + 4), footer, font=font(13, True), fill=ACCENT)
    return img


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(HERE / "problem_graph_discovery.gif"))
    ap.add_argument("--poster", default=str(HERE / "problem_graph_discovery_poster.png"))
    ap.add_argument("--frames", type=int, default=120)
    ap.add_argument("--duration", type=int, default=110, help="ms per frame")
    args = ap.parse_args(argv)

    data, pred, thomp, swarm = load()
    g = Graph(data)
    nodes = [n for n in g.nodes if n["status"] != "root"]
    attempts = [e for e in g.edges if e["from"] != "root"]
    cnt = Counter(n["status"] for n in nodes)
    agents = len({e["agent"] for e in attempts})
    tallies = (pred or {}).get("tallies", {})
    n_pred = len((pred or {}).get("predictions", []))
    n_claims = (thomp or {}).get("n", 0)
    n_open = len(swarm["problems"])
    all_ids = {n["id"] for n in g.nodes}

    # camera targets (graph coords), from the actual node layout
    def bbox(ids, pad=70):
        ns = [g.by_id[i] for i in ids if i in g.by_id]
        return (min(n["x"] for n in ns) - pad, min(n["y"] for n in ns) - pad - 40,
                max(n["x"] for n in ns) + NW + pad, max(n["y"] for n in ns) + NH + pad)

    pred_ids = [n["id"] for n in g.nodes if n["family"] == "Registered predictions"]
    cam_pred = bbox(pred_ids, 80)

    # The definitive roll: graph status solved (positively shown) + refuted
    # (negatively shown), in graph order -- but ONLY scientifically important
    # facts this project is validating. Audit scores, agent assessments,
    # code pruning, publishing infrastructure and methods-guide verdicts are
    # real work, yet they are not scientific results, so they are excluded
    # here by node id (they remain in the graph itself). A bare node label
    # does NOT say what was shown, so every entry carries a plain statement
    # of the actual result, grounded in that node's sub/detail on the graph
    # page. The >=10-word floor is asserted below: a future definitive node
    # without a statement this long fails the build instead of scrolling a
    # mystery.
    PROCESS_EXCLUDED = {
        "f3": "audit re-score process, not a scientific claim",
        "r6": "Bayesian Delphi panel: agents forced to justify themselves showed no reliable path -- an assessment outcome, not a scientific result",
        "r8": "code pruning to the core theorem suite",
        "b6": "knowledge-graph / nanopublication infrastructure",
        "tch-2": "Thompson Ch. II claims settled elsewhere, not validated here",
        "r7": "autonomous overnight-loop process failure, not a scientific claim",
        "l3": "causal-emergence methods-guide verdict, not a validated fact",
    }
    DEFINITIVE = {
        "t1": "Nine of seventeen landmarks sit inside the head and none on fin margins, so landmark fitting measurably worsens whole-body silhouette overlap.",
        "t2": "Fitting Thompson's five-to-eight-parameter families directly to 600 outline semilandmarks recovers all six fish pairs diffeomorphically, bijectively, and reversibly throughout.",
        "t4": "Across 791 species and 4,334 dated divergence pairs, global grids hold below roughly fifty million years before modularity dominates.",
        "r0": "The mantle-edge cellular-automaton pattern maps onto a Raup shell at IoU 0.835, and the neural gate is proved bit-for-bit Rule 30.",
        "r1": "Left-cone diagonals follow an autonomous recurrence: odd-parity barriers double the period, even-parity barriers split into a binary barrier tree.",
        "r2": "The carry-lookahead operator proves period grows without bound for powers of two, and the causal solver resolves the fifth doubling exactly.",
        "r3": "The lock-in envelope is proved unconditionally non-decreasing, and centre periods one and two are eliminated for every starting offset.",
        "l1": "The Zhang sorting replication was audited against the pinned upstream repository and independently ported across Python, C++, JavaScript and Lean.",
        "ZF-TUR-01": "Zebrafish BMP patterning is not free diffusion: Chordin shuttling plus tolloid release makes Chordin mobility exceed the free-diffusion size prior.",
        "ZF-TUR-02": "Blocking tolloid cleavage leaves more intact Chordin, contracts the ventral pSmad signalling domain, and dorsalizes the developing zebrafish embryo phenotype.",
        "DM-WG-01": "Wingless spread requires Porcupine lipidation at Ser239; blocking it collapses the Wingless distribution back onto only its producing cells.",
        "DM-HH-01": "The signalling species is the 173-amino-acid dually lipidated HhN; cholesterol loss spreads signal farther but lowers peak response near source.",
        "DM-DPP-01": "The diffusible Dpp species is the 132-amino-acid mature chain, not the 588-amino-acid precursor, correcting mobility estimates based on molecular size.",
        "DM-CLK-NEG-01": "Confirmed negative: Drosophila has no travelling Hes/her segmentation wavefront; long-germ pair-rule stripes form near-simultaneously, refuting the clock-wavefront assignment entirely.",
        "XT-BMP-01": "Xenopus Noggin patterns the dorsal-ventral axis by binding BMP4 directly; misexpression dorsalizes embryos, while Noggin loss ventralizes them measurably.",
        "XT-SHH-01": "Xenopus Shh proves dually lipidated like its orthologs, carrying N-palmitate and C-cholesterol despite the UniProt entry annotating no lipidation.",
        "XT-DQ-01": "The UniProt accession linked to Xenopus BMP4 is only a 69-amino-acid fragment, invalidating protein conclusions until the 469-amino-acid re-resolution.",
        "t3": "A four-parameter rectangular box stretch explains most unlabeled silhouette gain, but fails homologous perimeter landmarks where Thompson's warps win clearly.",
        "f5": "Static single-wavelength Turing patterning is rejected for Holstein coats; held-out morphometric distance 6.46 versus roughly 3.3 for the alternatives tested.",
        "f4": "Ensembl Compara shows Xenopus bmp4 and nog are not orthologs of zebrafish bmp2b and chd, and the protein size prior independently splits them.",
        "b2": "The hash-locked Xenopus neighbour test scored chance-level AUC 0.484; orientation alone carried the signal, not calcium-wave features themselves at all.",
        "b4": "All four hash-locked Zebrahub zebrafish predictions failed the registered scoring after checksum verification, giving zero successes from four attempts total.",
    }
    all_definitive = [n for n in g.order if n["status"] in ("solved", "refuted")]
    unknown_excl = [i for i in PROCESS_EXCLUDED if i not in {n["id"] for n in all_definitive}]
    definitive_nodes = [n for n in all_definitive if n["id"] not in PROCESS_EXCLUDED]
    missing = [n["id"] for n in definitive_nodes if n["id"] not in DEFINITIVE]
    stray = [i for i in DEFINITIVE if i not in {n["id"] for n in definitive_nodes}]
    short = [i for i, s in DEFINITIVE.items() if len(s.split()) < 10]
    if missing or short or unknown_excl or stray:
        raise SystemExit(f"definitive roll needs a >=10-word scientific statement per shown node; "
                         f"missing={missing} short={short} unknown_excluded={unknown_excl} stray={stray}")
    positive = [(n, DEFINITIVE[n["id"]]) for n in definitive_nodes if n["status"] == "solved"]
    negative = [(n, DEFINITIVE[n["id"]]) for n in definitive_nodes if n["status"] == "refuted"]

    # Pre-render the scrolling definitive roll (tall image, cropped per frame)
    def build_roll():
        LW, x = 1204, 26
        entries = []  # (kind, node, statement)
        entries.append(("head+", None, f"POSITIVELY SHOWN — {len(positive)}"))
        entries += [("item", n, s) for n, s in positive]
        entries.append(("head-", None, f"NEGATIVELY SHOWN / REFUTED — {len(negative)}"))
        entries += [("item", n, s) for n, s in negative]
        entries.append(("foot", None, ""))
        # measure
        heights = []
        for kind, n, s in entries:
            if kind.startswith("head"):
                heights.append(40)
            elif kind == "foot":
                heights.append(96)
            else:
                lines = textwrap.wrap(s, width=118)
                heights.append(26 + 16 * len(lines) + 10)
        img = Image.new("RGB", (LW, sum(heights)), (255, 255, 255))
        d = ImageDraw.Draw(img)
        y = 0
        for (kind, n, s), h in zip(entries, heights):
            if kind.startswith("head"):
                col = SCOL["solved"] if kind == "head+" else SCOL["refuted"]
                d.rectangle([0, y, LW, y + h], fill=(240, 248, 243) if kind == "head+" else (250, 240, 240))
                d.text((x, y + 10), ("✓  " if kind == "head+" else "✗  ") + s, font=font(16, True), fill=col)
            elif kind == "foot":
                d.text((x, y + 14), f"{len(positive) + len(negative)} scientific claims settled definitively · audit / infrastructure / process nodes excluded from this roll",
                       font=font(13, True), fill=INK)
                d.text((x, y + 42), "Explore the full graph, with sources per claim:  fractastical.github.io/morpholib/problem-graph.html",
                       font=font(12), fill=ACCENT)
                d.text((x, y + 64), "Refuted branches stay in the graph — pruned in place, never deleted. Negative results are results.",
                       font=font(12), fill=MUT)
            else:
                mark, col = ("✓", SCOL["solved"]) if n["status"] == "solved" else ("✗", SCOL["refuted"])
                d.text((x, y + 3), mark, font=font(13, True), fill=col)
                name = n["label"] if n["family"] != "Registered predictions" else f"{n['label']} — {n['sub'].split('·')[0].strip()}"
                d.text((x + 24, y + 3), name, font=font(13, True), fill=INK)
                ly = y + 22
                for ln in textwrap.wrap(s, width=118):
                    d.text((x + 24, ly), ln, font=font(11), fill=(55, 55, 60))
                    ly += 16
                d.line([x, y + h - 2, LW - 10, y + h - 2], fill=(238, 238, 234))
            y += h
        return img

    roll = build_roll()
    N = args.frames
    frames: list[Image.Image] = []

    for i in range(N):
        t = i / (N - 1)
        # ---- scene boundaries (fractions of the loop) ----
        if t < 0.09:  # 1 TITLE
            img = g.view(g.full, all_ids, focus=None, dim_others=False)
            img = img.point(lambda v: int(v * 0.45 + 255 * 0.55))
            banner(img, "Project Delphi — the discovery problem graph",
                   "Is biological form law-like, predictable & machine-checkable?")
            p = smooth(min(1, t / 0.07))
            stats = [("problems attempted", len(nodes), INK), ("solution attempts (edges)", len(attempts), INK),
                     ("agents on record", agents, INK), ("shown definitively", cnt["solved"], SCOL["solved"]),
                     ("definitively refuted", cnt["refuted"], SCOL["refuted"]), ("still open", cnt["open"], SCOL["open"])]
            stat_panel(img, (300, 200, 940, 510), "Every problem attempted, 1917–2026",
                       [(lab, int(val * p), col) for lab, val, col in stats],
                       footer="Every branch kept — including the ones that failed.")
        elif t < 0.30:  # 2 BUILD, lane by lane
            p = smooth((t - 0.09) / 0.21)
            k = int(round(p * len(g.order)))
            visible = {n["id"] for n in g.order[:k]}
            img = g.view(g.full, visible)
            banner(img, "How the graph was built — paper → reproduction → audit → branch",
                   f"{k}/{len(g.order)} problems on the board · edge colour = the agent that tried that step")
        elif t < 0.42:  # 3 OUTCOME SWEEP
            p = (t - 0.30) / 0.12
            focus = {"solved"} if p < 0.5 else {"refuted", "open"}
            img = g.view(g.full, all_ids, focus=focus, dim_others=True)
            banner(img, "Outcomes, honestly kept",
                   "solved / proved" if p < 0.5 else "refuted branches are pruned in place — never deleted")
            stat_panel(img, (18, 540, 420, 682), "Status of every problem",
                       [(SLAB[s], cnt[s], SCOL[s]) for s in ("solved", "partial", "open", "refuted")])
        elif t < 0.56:  # 4 REGISTERED PREDICTIONS ZOOM
            p = (t - 0.42) / 0.14
            cam = lerp(g.full, cam_pred, smooth(min(1, p * 2.2)))
            img = g.view(cam, all_ids)
            banner(img, "Registered predictions — outcome AND resolvability, scored",
                   f"registered {pred['registered_on']} before scoring · Thompson: {n_claims} claims browsed from the same graph")
            stat_panel(img, (730, 500, 1222, 682), "Scoreboard (hash-locked, then scored)",
                       [("registered predictions", n_pred, INK),
                        ("confirmed", tallies.get("confirmed", 0), SCOL["solved"]),
                        ("partially resolved", tallies.get("partially_resolved", 0), SCOL["partial"]),
                        ("refuted", tallies.get("refuted", 0), SCOL["refuted"])],
                       footer="each partial names its missing series")
        else:  # 5 FINALE -- scrolling roll of every definitive claim, either way
            p = (t - 0.56) / 0.44
            img = Image.new("RGB", (W, H), BG)
            banner(img, "Scientific claims shown definitively — positively or negatively",
                   "Only facts being validated (≥10 words each) — audit, infrastructure and agent-process points excluded")
            vh = 682 - 82
            max_off = max(0, roll.height - vh)
            # scroll over the first 82% of the scene, then hold the foot
            off = int(max_off * min(1, p / 0.82))
            img.paste(roll.crop((0, off, roll.width, off + vh)), (18, 82))
            d = ImageDraw.Draw(img)
            d.rounded_rectangle([18, 82, 1222, 682], radius=10, outline=LINE, width=2)
            # scroll progress tick
            if max_off:
                th = max(24, int(vh * vh / roll.height))
                ty = 82 + int((vh - th) * (off / max_off))
                d.rounded_rectangle([1212, ty, 1218, ty + th], radius=3, fill=(170, 170, 165))
        frames.append(img)

    frames[-1].save(args.poster)
    # one shared palette (from title / build / finale) -- no per-frame flicker
    strip = Image.new("RGB", (W, H * 3))
    for j, f in enumerate((frames[4], frames[N // 3], frames[-1])):
        strip.paste(f, (0, j * H))
    pal = strip.quantize(colors=128, method=Image.MEDIANCUT)
    q = [f.quantize(palette=pal, dither=Image.FLOYDSTEINBERG) for f in frames]
    out = Path(args.out)
    q[0].save(out, save_all=True, append_images=q[1:], duration=args.duration, loop=0, optimize=True)
    print(f"saved {out}  {W}x{H}, {len(q)} frames, {out.stat().st_size // 1024} KiB")
    print(f"saved {args.poster}")
    print(f"graph: {len(nodes)} problems, {len(attempts)} attempts, statuses {dict(cnt)}; "
          f"predictions {n_pred} (tallies {tallies}); claims {n_claims}; open queue {n_open}")
    print(f"definitive roll: {len(positive)} shown + {len(negative)} refuted scientific claims, "
          f"statement word counts {min(len(s.split()) for _, s in positive + negative)}"
          f"–{max(len(s.split()) for _, s in positive + negative)} words (floor 10 asserted); "
          f"excluded as audit/infrastructure/process: {sorted(PROCESS_EXCLUDED)}")


if __name__ == "__main__":
    main()
