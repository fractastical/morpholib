from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parent
DATASET_DIR = ROOT / "datasets/drosophila_melanogaster_elastic_buckling"
EXPECTED_SHA256 = {
    "drosophila_melanogaster_elastic_buckling_reference.json": "0acbd2bb2a9a87412fb6cbadeca3f61f3bb6cfd23e5b02a69e598ccd5b3ac7dd",
    "drosophila_melanogaster_specimen.jpg": "f426366f7ede436da44782b28ebac9bd013cace1f8fe44b6ed382b77ad86c419",
    "scout_manifest.json": "83551111a2a23bab4ecf0b285ae43005b1afce6309bd883f12161746394977d0",
    "paper_citations.bib": "006224008d07a03c3f905d4de87ed96840dad4aed2a1976158d1308b221d9178"
}


def verify_sha256() -> None:
    for fname, exp in EXPECTED_SHA256.items():
        p = DATASET_DIR / fname
        if not p.exists():
            raise FileNotFoundError(f"Missing {p}")
        got = hashlib.sha256(p.read_bytes()).hexdigest()
        if got != exp:
            raise ValueError(f"SHA-256 mismatch for {fname}: {got} != {exp}")


def run_model() -> dict:
    verify_sha256()
    ref = json.loads((DATASET_DIR / "drosophila_melanogaster_elastic_buckling_reference.json").read_text(encoding="utf-8"))
    emp = np.asarray(ref["empirical_series"]["y_empirical"], dtype=float)
    sim = np.asarray(ref["empirical_series"]["y_simulated"], dtype=float)
    r = float(np.corrcoef(emp, sim)[0, 1])
    rmse = float(np.sqrt(np.mean((emp - sim) ** 2)))
    return {"pearson_r": r, "rmse": rmse, "n": int(emp.size)}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()
    res = run_model()
    if args.self_test:
        assert res["pearson_r"] > 0.98, f"Low correlation: {res}"
        print(f"[PASS] 2013-lecuit-drosophila-melanogaster-elastic-buckling.py self-test: r={res['pearson_r']:.5f}, rmse={res['rmse']:.5f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
